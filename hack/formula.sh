#!/usr/bin/env bash
# Write Formula/pats.rb for a published release, from its checksums.txt.
#
# Usage: formula.sh <version>      # e.g. 1.0.2, no leading v
set -euo pipefail

cd "$(dirname "$0")/.."

REPO="lczyk/pats"
OUT="Formula/pats.rb"

_sha() {
    local sums="$1" name="$2" sum
    sum=$(grep -F "  ${name}" <<< "${sums}" | cut -d' ' -f1)
    if [ -z "${sum}" ]; then
        printf 'no checksum for %s\n' "${name}" >&2
        exit 1
    fi
    printf '%s' "${sum}"
}

main() {
    local v="${1:-}"
    case "${v}" in
        ("" | v* | *-*)
            printf 'usage: %s <version>, a stable one without the v\n' "$0" >&2
            exit 2
            ;;
    esac

    local base="https://github.com/${REPO}/releases/download/v${v}"
    local sums
    sums=$(curl -fsSL "${base}/checksums.txt")

    local da dx la lx
    da=$(_sha "${sums}" "pats_${v}_darwin_arm64.tar.gz")
    dx=$(_sha "${sums}" "pats_${v}_darwin_amd64.tar.gz")
    la=$(_sha "${sums}" "pats_${v}_linux_arm64.tar.gz")
    lx=$(_sha "${sums}" "pats_${v}_linux_amd64.tar.gz")

    mkdir -p "$(dirname "${OUT}")"
    cat > "${OUT}" <<EOF
# generated by hack/formula.sh (make formula V=<version>), do not edit by hand.
class Pats < Formula
  desc "Score-based testing framework for agent tasks"
  homepage "https://github.com/${REPO}"
  version "${v}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/pats_${v}_darwin_arm64.tar.gz"
      sha256 "${da}"
    end
    on_intel do
      url "${base}/pats_${v}_darwin_amd64.tar.gz"
      sha256 "${dx}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/pats_${v}_linux_arm64.tar.gz"
      sha256 "${la}"
    end
    on_intel do
      url "${base}/pats_${v}_linux_amd64.tar.gz"
      sha256 "${lx}"
    end
  end

  def install
    bin.install "pats"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/pats --version")
  end
end
EOF
    printf 'wrote %s for v%s\n' "${OUT}" "${v}" >&2
}

main "$@"
